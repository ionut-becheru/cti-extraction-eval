#!/usr/bin/env python3
"""Aggregate all experiment outputs into paper tables (LaTeX under paper/tables/, Markdown under experiments/tables.md)
and a machine-readable paper_numbers.json (every number with its run ID).

Usage: python aggregate_tables.py
"""
import json, pathlib, glob, collections, re
EXP = pathlib.Path(__file__).resolve().parent.parent; ROOT = EXP; RUNS = EXP / 'runs'; TAB = EXP / 'paper_tables'; TAB.mkdir(parents=True, exist_ok=True)
DS = ['aptner', 'dnrti', 'cyner', 'annoctr', 'attacker']; DSN = {'aptner': 'APTNER', 'dnrti': 'DNRTI', 'cyner': 'CyNER', 'annoctr': 'AnnoCTR', 'attacker': 'AttackER'}
numbers = {}; md = []

def f(x, d=3): return f'{x:.{d}f}' if isinstance(x, (int, float)) else str(x)
def ci(m, k='F1'): return f"[{m['ci95'][k][0]:.2f}, {m['ci95'][k][1]:.2f}]" if 'ci95' in m and k in m['ci95'] else ''
WIDE = {'T10_mt_systems', 'T2_indomain', 'T2b_fine', 'T4_noise', 'T5_relevance', 'T8_hybrid', 'T9_ioc_corruption', 'T7_cost'} | {f'T3_transfer_{t}' for t in ('roberta', 'deberta-v3', 'securebert20')}
COLSPEC = {}

def tex_table(name, caption, header, rows, label, note=''):
    wide = name in WIDE; env = 'table*' if wide else 'table'; width = r'\textwidth' if wide else r'\linewidth'
    cols = COLSPEC.get(name, 'l' + 'r' * (len(header) - 1)); resize = name not in COLSPEC
    L = [f'% generated by experiments/scripts/aggregate_tables.py', r'\begin{' + env + '}[t]', r'\centering', r'\caption{' + caption + '}', r'\label{' + label + '}', r'\small']
    if resize: L.append(r'\begin{adjustbox}{max width=' + width + '}')
    L += [r'\begin{tabular}{' + cols + '}', r'\toprule', ' & '.join(header) + r' \\', r'\midrule'] + [' & '.join(r) + r' \\' for r in rows] + [r'\bottomrule', r'\end{tabular}']
    if resize: L.append(r'\end{adjustbox}')
    if note: L.append(r'\\[2pt]\parbox{' + width + r'}{\footnotesize ' + note + '}')
    L.append(r'\end{' + env + '}'); (TAB / f'{name}.tex').write_text('\n'.join(L))
    md.append(f'\n### {name}: {caption}\n\n| ' + ' | '.join(header) + ' |\n|' + '---|' * len(header) + '\n' + '\n'.join('| ' + ' | '.join(r) + ' |' for r in rows) + ('\n\n' + note if note else ''))

