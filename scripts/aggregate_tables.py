rows = []
for t in types:
    r = [t.replace('_', r'\_')]
    for ds in DS:
        m = g[f'{ds}_test']['metrics'].get(t)
        r.append('--' if m is None or m['n_gold'] == 0 else f"{m['P']:.2f}/{m['R']:.2f}")
    rows.append(r)
r = [r'\textbf{micro F1 (strict)}']
for ds in DS:
    m = g[f'{ds}_test']['metrics']['MICRO_ALL']; r.append(f"\\textbf{{{m['F1']:.3f}}} {ci(m)}"); numbers[f'T1.gazetteer_microF1.{ds}'] = {'value': m['F1'], 'ci95': m['ci95']['F1'], 'run': 'N0_dictionary_ner'}
rows.append(r); rows.append(['gold mentions not expressible'] + [f"{g[f'{ds}_test']['gold_uncovered_pct']}\\%" for ds in DS])
tex_table('T1_gazetteer_audit', "Thesis regex+gazetteer extractor against gold test sets: precision/recall per coarse type (strict span match) and micro-F1 with 95\\% bootstrap CIs. ``--'': type not annotated in that corpus.",
          ['Type'] + [DSN[d] for d in DS], rows, 'tab:gazetteer', 'Run N0\\_dictionary\\_ner. DNRTI merges malware and tools (MALWARE\\_TOOL); CyNER/AttackER merge IOC types (INDICATOR). Last row: share of gold mentions whose type the thesis schema cannot represent.')

# ---------------- T2: in-domain F1 all methods
def load_ft(tag, ds, schema='coarse', seed=13):
    p = RUNS / f'E2_ft/{tag}_{ds}_{schema}_s{seed}/metrics.json'
    return json.load(open(p)) if p.exists() else None
methods = [('Regex+gazetteer (thesis)', lambda ds: g[f'{ds}_test']['metrics']['MICRO_ALL'], 'N0_dictionary_ner')]
for tag, name in [('roberta', 'RoBERTa-base (ft)'), ('deberta-v3', 'DeBERTa-v3-base (ft)'), ('securebert20', 'SecureBERT~2.0-base (ft)')]:
    methods.append((name, (lambda tag: lambda ds: (load_ft(tag, ds) or {}).get('eval', {}).get(ds, {}).get('MICRO'))(tag), f'E2_ft/{tag}_*_coarse_s13'))
for zs, name in [('gliner_large', 'GLiNER-L v2.1 (0-shot)'), ('nuner_zero', 'NuNER-Zero (0-shot)')]:
    p = RUNS / f'E3_zs/{zs}/metrics.json'; z = json.load(open(p)) if p.exists() else None
    methods.append((name, (lambda z: lambda ds: (z or {}).get('eval', {}).get(ds, {}).get('metrics', {}).get('MICRO'))(z), f'E3_zs/{zs}'))
for llm, name in [('qwen3_8b_0shot', 'Qwen3-8B (0-shot)'), ('qwen3_8b_5shot', 'Qwen3-8B (5-shot)'), ('fsec8b_0shot', 'Foundation-Sec-8B-It (0-shot)'), ('fsec8b_5shot', 'Foundation-Sec-8B-It (5-shot)')]:
    p = RUNS / f'E4_llm/{llm}/metrics.json'; z = json.load(open(p)) if p.exists() else None
    methods.append((name, (lambda z: lambda ds: (z or {}).get('eval', {}).get(ds, {}).get('metrics', {}).get('MICRO'))(z), f'E4_llm/{llm}'))
rows = []
for name, fn, run in methods:
    r = [name]; any_ = False
    for ds in DS:
        m = fn(ds)
        if m: r.append(f"{m['F1']:.3f} / {m['F1_relaxed']:.3f}"); numbers[f'T2.{name}.{ds}'] = {'strict_F1': m['F1'], 'relaxed_F1': m['F1_relaxed'], 'ci95_strict': m.get('ci95', {}).get('F1'), 'run': run}; any_ = True
        else: r.append('--')
    if any_: rows.append(r)
# RoBERTa seed spread (13/17/19) as an extra row
import statistics
r = ['RoBERTa-base (ft), 3 seeds mean$\\pm$sd']; any_ = False
for ds in DS:
    fs = [json.load(open(p))['eval'][ds]['MICRO']['F1'] for p in sorted(glob.glob(str(RUNS / f'E2_ft/roberta_{ds}_coarse_s*/metrics.json')))]
    if len(fs) >= 2: r.append(f"{statistics.mean(fs):.3f}$\\pm${statistics.pstdev(fs):.3f}"); numbers[f'T2.roberta_seeds.{ds}'] = {'F1s': fs, 'mean': statistics.mean(fs), 'sd': statistics.pstdev(fs), 'run': f'E2_ft/roberta_{ds}_coarse_s13|17|19'}; any_ = True
    else: r.append('--')
if any_: rows.insert(2, r)
tex_table('T2_indomain', 'In-domain entity extraction, coarse schema, strict / relaxed micro-F1 on the original test splits. Fine-tuned encoders: 5 epochs, seed 13, dev-selected epoch. Zero-shot and LLM extractors are asked only for the types each corpus annotates.',
          ['Method'] + [DSN[d] for d in DS], rows, 'tab:indomain', 'Bootstrap CIs (1,000 resamples over sentences) are in paper\\_numbers.md. AttackER test has 131 sentences; its CIs are wide.')

# ---------------- T2b: fine-schema in-domain (original label sets) for comparison with the literature
rows = []
for tag, name in [('roberta', 'RoBERTa-base'), ('deberta-v3', 'DeBERTa-v3-base'), ('securebert20', 'SecureBERT~2.0-base')]:
    r = [name]
    for ds in DS:
        m = load_ft(tag, ds, 'fine')
        if m: e = m['eval'][ds]['MICRO']; r.append(f"{e['F1']:.3f} / {e['F1_relaxed']:.3f}"); numbers[f'T2b.{name}.{ds}'] = {'strict_F1': e['F1'], 'relaxed_F1': e['F1_relaxed'], 'ci95_strict': e['ci95']['F1'], 'n_labels': len(m['labels']), 'run': f'E2_ft/{tag}_{ds}_fine_s13'}
        else: r.append('--')
    rows.append(r)
rows.append(['fine types (BIO labels)'] + [str(len(load_ft('roberta', ds, 'fine')['labels'])) if load_ft('roberta', ds, 'fine') else '--' for ds in DS])
tex_table('T2b_fine', 'In-domain fine-tuning on each corpus\'s original label set (all types, none merged), strict / relaxed micro-F1 on the original test split, seed 13.', ['Model'] + [DSN[d] for d in DS], rows, 'tab:fine',
          'For reference, CyberNER~\\cite{echchammakhy2025cyberner} reports 0.792 (APTNER), 0.871 (DNRTI), 0.869 (CyNER) and 0.734 (AttackER) for the best of several fine-tuned encoders with a CRF layer, on the original splits of each corpus.')

# ---------------- T3: transfer matrix (best encoder = roberta unless deberta better on avg)
def transfer(tag):
    M = {}
    for src in DS:
        m = load_ft(tag, src)
        if not m: continue
        for tgt in DS:
            if tgt == src: M[(src, tgt)] = m['eval'][tgt]['MICRO']['F1']
            else:
                sh = (m.get('eval_shared_types') or {}).get(tgt)
                M[(src, tgt)] = (sh['metrics']['MICRO']['F1'] if sh and sh['metrics'] else None, m['eval'][tgt]['MICRO']['F1'])
    return M
for tag in ['roberta', 'deberta-v3', 'securebert20']:
    M = transfer(tag)
    if not M: continue
    rows = []
    for src in DS:
        r = [DSN[src]]
        for tgt in DS:
            v = M.get((src, tgt))
            if v is None: r.append('--')
            elif isinstance(v, tuple): r.append(('--' if v[0] is None else f'{v[0]:.2f}') + f' ({v[1]:.2f})')
            else: r.append(f'\\textbf{{{v:.2f}}}')
            numbers[f'T3.{tag}.{src}->{tgt}'] = {'value': v, 'run': f'E2_ft/{tag}_{src}_coarse_s13'}
        rows.append(r)
    tex_table(f'T3_transfer_{tag}', f'Cross-corpus transfer, {tag} fine-tuned on the row corpus (coarse schema), strict micro-F1 on the column corpus test split: on types shared by source and target (all target types in parentheses). Diagonal: in-domain.',
              ['train $\\downarrow$ / test $\\rightarrow$'] + [DSN[d] for d in DS], rows, f'tab:transfer_{tag}')

# ---------------- T4: noise
ns_p = EXP / 'data/gold_ner/noise_stats.json'; NS = json.load(open(ns_p)) if ns_p.exists() else {}
variants = ['bt-ru', 'bt-de', 'bt-zh', 'bt-es', 'defang', 'boiler', 'lower', 'typo']
METHOD_ORDER = [('gazetteer', 'Regex+gazetteer'), ('roberta', 'RoBERTa (ft)'), ('deberta-v3', 'DeBERTa-v3 (ft)'), ('securebert20', 'SecureBERT 2.0 (ft)'), ('gliner', 'GLiNER-L (0-shot)'), ('qwen3_0shot', 'Qwen3-8B (0-shot)')]
def noise_scores(tag, ds):
    d = RUNS / f'E5_noise/{tag}_{ds}'
    if tag == 'gazetteer':
        f = d / 'dictionary_ner_eval.json'
        if not f.exists(): return None
        m = json.load(open(f)); return {k: m[f'{k}_test']['metrics']['MICRO_ALL'] for k in [ds] + [f'{ds}__{v}' for v in variants] if f'{k}_test' in m}
    f = d / 'metrics.json'
    if not f.exists(): return None
    m = json.load(open(f))['eval']; out = {}
    for k in [ds] + [f'{ds}__{v}' for v in variants]:
        e = m.get(k)
        if e is None: continue
        out[k] = e['metrics']['MICRO'] if 'metrics' in e else e['MICRO']
    return out
rows = []; any_noise = False
for ds in ['aptner', 'cyner', 'annoctr']:
    surv = ', '.join(f"{v[3:]} {100-NS.get(f'{ds}__{v}',{}).get('dropped_pct',0):.0f}\\%" for v in variants if v.startswith('bt-'))
    rows.append([f'\\multicolumn{{{len(variants)+2}}}{{l}}{{\\textit{{{DSN[ds]}}} (gold surviving BT verbatim: {surv})}}'])
    for tag, name in METHOD_ORDER:
        sc = noise_scores(tag, ds)
        if not sc: continue
        any_noise = True; r = [name, f"{sc[ds]['F1']:.2f}" if ds in sc else '--']
        for v in variants:
            k = f'{ds}__{v}'; r.append(f"{sc[k]['F1']:.2f}" if k in sc else '--')
            if k in sc: numbers[f'T4.{tag}.{k}'] = {'strict_F1': sc[k]['F1'], 'relaxed_F1': sc[k]['F1_relaxed'], 'ci95_strict': sc[k].get('ci95', {}).get('F1'), 'run': f'E5_noise/{tag}_{ds}'}
        rows.append(r)
if any_noise:
    tex_table('T4_noise', 'Extraction under noise: strict micro-F1 on the clean test set and on each noisy variant (MarianMT round trips EN$\\to$X$\\to$EN, IOC defanging, forum boilerplate, lower-casing, 5\\% typos). Back-translated sets are scored on gold mentions that survive translation verbatim.',
              ['Method', 'clean'] + variants, rows, 'tab:noise')

